  function applyLang(lang){
    if (!translations[lang]) return;
    var dict = translations[lang];
    document.documentElement.setAttribute('lang', lang);
    document.title = dict['meta.title'];
    var metaDesc = document.getElementById('metaDescription');
    if (metaDesc) metaDesc.setAttribute('content', dict['meta.description']);

    document.querySelectorAll('[data-i18n]').forEach(function(el){
      var key = el.getAttribute('data-i18n');
      if (dict[key] !== undefined) el.textContent = dict[key];
    });
    document.querySelectorAll('[data-i18n-html]').forEach(function(el){
      var key = el.getAttribute('data-i18n-html');
      if (dict[key] !== undefined) el.innerHTML = dict[key];
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(function(el){
      var key = el.getAttribute('data-i18n-placeholder');
      if (dict[key] !== undefined) el.setAttribute('placeholder', dict[key]);
    });
    document.querySelectorAll('[data-i18n-aria]').forEach(function(el){
      var key = el.getAttribute('data-i18n-aria');
      if (dict[key] !== undefined) el.setAttribute('aria-label', dict[key]);
    });
    document.querySelectorAll('.lang-switch button').forEach(function(btn){
      btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
    });
    try{ localStorage.setItem('opora-lang', lang); }catch(e){}
  }

  var initialLang = 'ru';
  try{
    var storedLang = localStorage.getItem('opora-lang');
    if (storedLang === 'en' || storedLang === 'ru') initialLang = storedLang;
  }catch(e){}
  applyLang(initialLang);

  document.querySelectorAll('.lang-switch button').forEach(function(btn){
    btn.addEventListener('click', function(){ applyLang(btn.getAttribute('data-lang')); });
  });

  // ============ Theme toggle ============
  var themeToggle = document.getElementById('themeToggle');
  function currentTheme(){
    return document.documentElement.getAttribute('data-theme') ||
      (window.matchMedia('(prefers-color-scheme: dark)').matches ? 'dark' : 'light');
  }
  themeToggle.addEventListener('click', function(){
    var next = currentTheme() === 'dark' ? 'light' : 'dark';
    document.documentElement.setAttribute('data-theme', next);
    try{ localStorage.setItem('opora-theme', next); }catch(e){}
  });

  // ============ Mobile menu toggle ============
  var topbar = document.getElementById('topbar');
  var menuToggle = document.getElementById('menuToggle');
  menuToggle.addEventListener('click', function(){
    var open = topbar.classList.toggle('open');
    menuToggle.setAttribute('aria-expanded', open ? 'true' : 'false');
  });
  document.querySelectorAll('.nav-links a').forEach(function(a){
    a.addEventListener('click', function(){
      topbar.classList.remove('open');
      menuToggle.setAttribute('aria-expanded', 'false');
    });
  });

  // ============ Scroll reveal ============
  var reduced = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
  var sheets = document.querySelectorAll('.sheet:not(.hero)');
  if (reduced) {
    sheets.forEach(function(s){ s.classList.add('visible'); });
  } else if ('IntersectionObserver' in window) {
    var io = new IntersectionObserver(function(entries){
      entries.forEach(function(e){ if (e.isIntersecting) { e.target.classList.add('visible'); io.unobserve(e.target); } });
    }, { threshold: 0.12 });
    sheets.forEach(function(s){ io.observe(s); });
  } else {
    sheets.forEach(function(s){ s.classList.add('visible'); });
  }

  // ============ Sheet rail active state ============
  var railLinks = document.querySelectorAll('.sheet-rail a');
  var sections = document.querySelectorAll('main > section[id]');
  if ('IntersectionObserver' in window && railLinks.length) {
    var railIo = new IntersectionObserver(function(entries){
      entries.forEach(function(entry){
        if (entry.isIntersecting) {
          railLinks.forEach(function(l){ l.classList.remove('active'); });
          var match = document.querySelector('.sheet-rail a[data-target="' + entry.target.id + '"]');
          if (match) match.classList.add('active');
        }
      });
    }, { rootMargin: '-45% 0px -45% 0px' });
    sections.forEach(function(s){ railIo.observe(s); });
  }

  // ============ Contact form (no backend — local confirmation only) ============
